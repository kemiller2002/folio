import fs from "node:fs";

const { version } = JSON.parse(fs.readFileSync("package.json", "utf8"));
if (typeof version !== "string" || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  throw new Error("package.json must provide the Folio package version");
}

const path = "src/runtime-version.js";
const source = `// Generated by tools/build-runtime-version.mjs from package.json. Do not edit.\nexport const FOLIO_VERSION = ${JSON.stringify(version)};\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(path) ? fs.readFileSync(path, "utf8") : "";
  if (current !== source) throw new Error(`${path} is stale; run npm run runtime:build`);
} else {
  fs.writeFileSync(path, source);
}
